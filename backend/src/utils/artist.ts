/**
 * Robust canonical artist lookup: handles spaces, dots, aliases, and punctuation
 */
export function getCanonicalArtist(input?: string | null): { name: string; bio?: string; birthDate?: string; imageUrl?: string; coverUrl?: string } | null {
    if (!input || typeof input !== 'string') return null;
    const clean = input
        .toLowerCase()
        .replace(/^(?:artist|itunes-artist|itunes|yt-artist|sp-artist|canonical)-/, '')
        .trim();
    const norm = clean.replace(/[^a-z0-9]/g, '');
    if (!norm) return null;

    if (CANONICAL_ARTISTS[clean]) return CANONICAL_ARTISTS[clean];
    if (ALIASES[clean] && CANONICAL_ARTISTS[ALIASES[clean]]) return CANONICAL_ARTISTS[ALIASES[clean]];

    for (const [key, val] of Object.entries(CANONICAL_ARTISTS)) {
        const keyNorm = key.toLowerCase().replace(/[^a-z0-9]/g, '');
        const nameNorm = val.name.toLowerCase().replace(/[^a-z0-9]/g, '');
        if (keyNorm === norm || nameNorm === norm) return val;
    }

    for (const [aliasKey, targetKey] of Object.entries(ALIASES)) {
        const aliasNorm = aliasKey.toLowerCase().replace(/[^a-z0-9]/g, '');
        if (aliasNorm === norm && CANONICAL_ARTISTS[targetKey]) {
            return CANONICAL_ARTISTS[targetKey];
        }
    }

    return null;
}

/**
 * Splits compound artist strings into individual, canonical artists
 * Handles: "A, B & C", "A feat. B", "A with B", "A / B"
 */
export function splitArtistString(rawArtist: string): string[] {
    if (!rawArtist) return [];
    const parts = rawArtist
        .split(/\s*(?:,|&|\||\band\b|\bfeat\.?\b|\bft\.?\b|\bwith\b|\bvs\.?\b|\/|;|\s{2,})\s*/i)
        .map(p => p.trim())
        .filter(p => p.length > 0 && !/^(official|topic|various artists|vevo)$/i.test(p));

    const seen = new Set<string>();
    const result: string[] = [];
    for (const p of parts) {
        const normalized = normalizeArtistName(p);
        const normKey = normalized.toLowerCase().trim();
        if (!seen.has(normKey)) {
            seen.add(normKey);
            result.push(normalized);
        }
    }
    return result.length > 0 ? result : [normalizeArtistName(rawArtist)];
}

export function normalizeArtistName(name: string): string {
    if (!name) return "Unknown Artist";

    let normalized = name.toLowerCase().trim();

    // Check aliases first (direct match)
    if (ALIASES[normalized]) {
        return CANONICAL_ARTISTS[ALIASES[normalized]].name;
    }

    // Secondary cleanup
    const cleanName = normalized.replace(/,.*$/, "").replace(/&.*$/, "").replace(/\s+feat\..*$/i, "").trim();
    if (ALIASES[cleanName]) {
        return CANONICAL_ARTISTS[ALIASES[cleanName]].name;
    }

    // Check if it matches a canonical artist (Fuzzy search)
    for (const key in CANONICAL_ARTISTS) {
        if (normalized.includes(key) || key.includes(normalized)) {
            // Only return if it's a reasonably close match (length check)
            if (Math.abs(normalized.length - key.length) < 6) {
                return CANONICAL_ARTISTS[key].name;
            }
        }
    }

    return name.trim();
}

/**
 * Checks if an artist name is a dummy identifier or purely numeric (e.g., "itunes artist 480976476" or "480976476")
 */
export function isFakeOrNumericArtistName(name?: string | null): boolean {
    if (!name) return true;
    const clean = name.trim().toLowerCase();
    if (/^(itunes\s*artist\s*\d+|\d+|unknown\s*artist|artist\s*\d+)$/i.test(clean)) return true;
    if (/^\d{4,}$/.test(clean)) return true;
    return false;
}

/**
 * Cleans and deduplicates track artists to top 1-3 genuine names (composers + singers).
 * Strips junk channels, record labels, YouTube descriptions, cast lists, etc.
 */
export function cleanArtistNames(singers?: string | null, music?: string | null): string {
    const parts: string[] = [];
    if (music && music.trim()) {
        parts.push(...music.split(/[,\/&|;]/).map(s => s.trim()));
    }
    if (singers && singers.trim()) {
        parts.push(...singers.split(/[,\/&|;]/).map(s => s.trim()));
    }
    const clean: string[] = [];
    const seen = new Set<string>();
    for (const p of parts) {
        let norm = p.replace(/^[\s,;&/|•·\-–—]+|[\s,;&/|•·\-–—]+$/g, '').replace(/\s+/g, ' ').trim();
        if (!norm) continue;
        // Drop labels, metadata keywords, editors, etc.
        if (/music|records|audio|t-series|sony|speed|entertainment|channel|editor|soundtrack|vevo|topic|official/i.test(norm)) continue;
        // Strip trailing parens like "(Singer)" or "[Composer]"
        norm = norm.replace(/\s*[\(\[].*?[\)\]]/g, '').trim();
        if (!norm || isFakeOrNumericArtistName(norm)) continue;
        const normalized = normalizeArtistName(norm);
        const lower = normalized.toLowerCase();
        if (!seen.has(lower)) {
            seen.add(lower);
            clean.push(normalized);
            if (clean.length >= 3) break; // Top 1-3 names only!
        }
    }
    return clean.length > 0 ? clean.join(', ') : (singers || music ? normalizeArtistName((singers || music)!) : 'Various Artists');
}
